export function enrichCoin(symbol: string, baseAsset: string, quoteAsset = "USDT"): CoinMetadata {
  const cleanBase = baseAsset.toUpperCase();
  const known = KNOWN_COINS_MAP[cleanBase];
  return {
    symbol,
    baseAsset: cleanBase,
    quoteAsset,
    name: known ? known.name : cleanBase,
    category: known ? known.category : "all",
    isPopular: known ? Boolean(known.isPopular) : false,
  };
}

